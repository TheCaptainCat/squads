#: The creations that answer the ETag of the item they created or activated.
_ETAG_CREATES: frozenset[str] = frozenset(
    {"items.create", "roles.add", "roles.activate", "skills.add", "operators.add"}
)

_ETAG_PREFIXES: tuple[str, ...] = (
    "/v1/items/{id}",
    "/v1/roles/{addr}",
    "/v1/skills/{addr}",
    "/v1/operators/{addr}",
)


@functools.cache
def _group_of() -> dict[str, str]:
    return {name: group for group, names in _GROUPS for name in names}


@functools.cache
def _table() -> tuple[Operation[Any, Any], ...]:
    return tuple(__getattr__(name) for name in _ORDER)


@functools.cache
def _routed() -> tuple[Operation[Any, Any], ...]:
    return tuple(op for op in _table() if not op.local_only)


def __getattr__(name: str) -> Any:
    """An operation constant, or the whole table, imported when first asked for."""
    if name == "OPERATIONS":
        return _table()
    if name == "ROUTED_OPERATIONS":
        return _routed()
    group = _group_of().get(name)
    if group is None:
        raise AttributeError(f"module {__name__!r} has no attribute {name!r}")
    return getattr(importlib.import_module(f"squads._api._ops_{group}"), name)


def carries_etag(op: Operation[Any, Any]) -> bool:
    """Whether *op* answers the ETag of the item it addresses: every operation under an item or a
    roster entry, with any method, and the creations. It is absent only when the item's file is
    gone."""
    if op.name in _ETAG_CREATES:
        return True
    path = op.path
    return path is not None and any(path == p or path.startswith(p + "/") for p in _ETAG_PREFIXES)
