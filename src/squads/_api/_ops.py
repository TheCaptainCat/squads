"""The operation table: one entry per operation, the single source of the routes, the
request and response types and how each runs.

Each resource group defines its operations in its own module (``_ops_<group>.py``), so a
command imports only the operations, and the DTOs, it uses. This module answers every
operation constant by name, and the whole table as :data:`OPERATIONS`, importing a group
on first use. A new operation is defined in its group's module, listed in :data:`_ORDER`
(the order is the route priority) and in :data:`_GROUPS`."""

