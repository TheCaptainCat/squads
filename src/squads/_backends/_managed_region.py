"""Backend-neutral "managed region" wrapper: markers plus the tool-generated warning.

Every ``AgentBackend`` that maintains a squads-managed section inside a user-owned file
(``CLAUDE.md``, ``AGENTS.md``, …) delimits it with the ``squads:start``/``squads:end``
markers and stamps a "regenerated by `sq sync`; do not edit by hand" warning just inside
them (the ``AgentBackend`` contract, see ``_base.py``). ``wrap()``/``inject()`` are the
shared mechanism, so a per-file wrapper (``_claude_code/_claude_md.py``,
``_agents_md/_managed.py``) only supplies its file-specific "create if missing" header.
"""

from pathlib import Path

from squads import _aio
from squads._sections import conform_line_endings

START = "<!-- squads:start -->"
END = "<!-- squads:end -->"
WARNING = "<!-- managed by squads — regenerated by `sq sync`; do not edit by hand. -->"


def wrap(section_body: str) -> str:
    """Delimit *section_body* with the managed markers and the tool-generated warning."""
    return f"{START}\n{WARNING}\n{section_body.rstrip()}\n{END}\n"


async def inject(target: Path, section_body: str, *, missing_header: str) -> bool:
    """Insert or replace the managed section in *target*, preserving everything else.

    *missing_header* is prepended only when *target* does not exist yet: the caller's
    file-specific scaffold text. This module owns only the marker and warning mechanics.

    Returns ``True`` exactly when the block was inserted into a pre-existing file that already
    carried hand-written content and no ``squads:start``/``squads:end`` markers; the caller
    should warn that the co-resident hand-written model may contradict the managed instructions.
    The block is prepended in that case so the authoritative instructions are read first. A new
    file and an already-managed file (replaced in place) return ``False``.
    """
    # Only part of the file is generated; the rest is the adopter's hand-written content, which
    # `sq sync` cannot reproduce. Every branch rewrites the whole file, so all use the atomic
    # primitive: a kill mid-write must never cost that content.
    block = wrap(section_body)
    if not await _aio.path_exists(target):
        await _aio.atomic_write_text(target, f"{missing_header}{block}")
        return False
    text = await _aio.read_text(target, verbatim=True)
    si, ei = text.find(START), text.find(END)
    if si != -1 and ei != -1:
        new = text[:si] + block.rstrip("\n") + text[ei + len(END) :]
        await _aio.atomic_write_text(target, conform_line_endings(text, new))
        return False
    if text.strip():
        # Real pre-existing hand-written content, no markers yet: lead with the managed
        # block (insert at the top) rather than appending below it.
        sep = "" if text.startswith("\n") else "\n"
        await _aio.atomic_write_text(target, conform_line_endings(text, f"{block}{sep}{text}"))
        return True
    # Blank/whitespace-only file: nothing to contradict — append quietly, as before.
    sep = "" if text.endswith("\n") else "\n"
    await _aio.atomic_write_text(target, conform_line_endings(text, f"{text}{sep}\n{block}"))
    return False
