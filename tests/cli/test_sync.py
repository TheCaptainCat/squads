def _ran_without_sq(interpreter: str, line: str, empty_path: Path) -> tuple[int, str]:
    """The exit code and output of *line* run by *interpreter* with nothing on the PATH."""
    ran = subprocess.run(
        [interpreter, "-c", line],
        env={"PATH": str(empty_path)},
        capture_output=True,
        text=True,
        check=False,
    )
    return ran.returncode, ran.stdout


@pytest.mark.covers("sync")
@pytest.mark.parametrize("shell", ["bash", "zsh"])
async def test_every_line_of_a_pointer_exits_0_and_names_its_command_when_sq_is_absent(
    seeded_project, invoke, tmp_path, shell
) -> None:
    interpreter = shutil.which(shell)
    if interpreter is None:
        pytest.skip(f"{shell} is not installed")
    await invoke(["sync"])
    lines = [
        line[2:-1]
        for line in (seeded_project.root / MANAGER_ROLE_SKILL)
        .read_text(encoding="utf-8")
        .splitlines()
        if line.startswith("!`")
    ]
    assert len(lines) == 3
    for line in lines:
        assert _ran_without_sq(interpreter, line, tmp_path) == (
            0,
            line.split("echo '")[1].removesuffix("'") + "\n",
        )


@pytest.mark.covers("sync")
async def test_sync_rewrites_the_managed_region_and_keeps_the_prose_around_it(
    seeded_project, invoke
) -> None:
    claude_md = seeded_project.root / "CLAUDE.md"
    text = claude_md.read_text(encoding="utf-8")
    edited = text.replace("## Agent roster", "## Agent roster\n\nHAND EDIT\n")
    claude_md.write_text("# Mine\n\n" + edited + "\nTail prose\n", encoding="utf-8")
    result = await invoke(["sync"])
    assert (result.exit_code, result.output) == (0, DONE)
    rewritten = claude_md.read_text(encoding="utf-8")
    assert rewritten.startswith("# Mine\n\n# Project guidance\n")
    assert rewritten.endswith("\nTail prose\n")
    assert "- **Catherine Manager** — manager (`manager`)" in region(claude_md)
    assert "HAND EDIT" not in rewritten


@pytest.mark.covers("sync")
async def test_sync_on_current_files_only_reports_that_it_ran(seeded_project, invoke) -> None:
    result = await invoke(["sync"])
    assert (result.exit_code, result.output) == (0, DONE)


@pytest.mark.covers("sync", "--json")
async def test_sync_json_prints_what_the_regeneration_left_alone(seeded_project, invoke) -> None:
    skill = seeded_project.root / SKILL
    skill.write_text("junk", encoding="utf-8")
    result = await invoke(["sync", "--json"])
    assert result.exit_code == 0, result.output
    assert (
        result.output
        == json.dumps(
            {
                "skipped": [
                    ".claude/skills/squads/SKILL.md: out of date or edited by hand — "
                    "regenerated by this sync (backend: claude_code)"
                ]
            },
            indent=2,
        )
        + "\n"
    )
