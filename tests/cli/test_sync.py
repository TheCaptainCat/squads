@pytest.mark.covers("sync", "--json")
async def test_sync_json_prints_what_the_regeneration_left_alone(seeded_project, invoke) -> None:
    skill = seeded_project.root / SKILL
    skill.write_text("junk", encoding="utf-8")
    result = await invoke(["sync", "--json"])
    assert result.exit_code == 0, result.output
    assert (
        result.output
        == json.dumps(
            {
                "skipped": [
                    ".claude/skills/sq-how-to/SKILL.md: out of date or edited by hand — "
                    "regenerated by this sync (backend: claude_code)"
                ]
            },
            indent=2,
        )
        + "\n"
    )


@pytest.mark.covers("sync")
async def test_sync_leaves_one_instruction_to_invoke_sq_greeting_in_the_managed_section(
    seeded_project, invoke
) -> None:
    assert (await invoke(["sync"])).exit_code == 0
    text = "\n".join(region(seeded_project.root / "CLAUDE.md"))
    assert text.count("invoke the `sq-greeting` skill and\ncomplete every step it gives") == 1
    for gone in ("Impersonation on greeting", "Start of a run", "greet them first"):
        assert gone not in text
    for kept in ("## Agent roster", "## Operators (people)", "## Working language"):
        assert kept in text
    assert "## Orchestration loop" in text


@pytest.mark.covers("sync")
async def test_sync_merges_the_skill_allow_rules_and_keeps_the_adopters_own(
    seeded_project, invoke
) -> None:
    settings = seeded_project.root / ".claude" / "settings.json"
    settings.write_text(
        json.dumps({"permissions": {"allow": ["Bash(make:*)"], "deny": ["Bash(rm:*)"]}}),
        encoding="utf-8",
    )
    assert (await invoke(["sync"])).exit_code == 0
    permissions = json.loads(settings.read_text(encoding="utf-8"))["permissions"]
    assert permissions["deny"] == ["Bash(rm:*)"]
    assert permissions["allow"][0] == "Bash(make:*)"
    assert {"Bash(sq:*)", "Skill(sq-greeting)", "Skill(sq-how-to)"} <= set(permissions["allow"])
