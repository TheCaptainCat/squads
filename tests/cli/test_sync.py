DONE = "synced managed files to this squads version\n"
SKILL = Path(".claude/skills/squads/SKILL.md")
POINTER = Path(".claude/agents/manager.md")


@pytest.mark.covers("sync")
async def test_sync_restores_a_hand_edited_pointer_and_skill(seeded_project, invoke) -> None:
    root = seeded_project.root
    pointer, skill = root / POINTER, root / SKILL
    pointer.write_text(pointer.read_text(encoding="utf-8") + "HAND EDIT\n", encoding="utf-8")
    skill.write_text("junk", encoding="utf-8")
    result = await invoke(["sync"])
    assert (result.exit_code, result.output) == (
        0,
        "warning: .claude/agents/manager.md: out of date or edited by hand — regenerated by "
        "this sync (backend: claude_code)\n"
        "warning: .claude/skills/squads/SKILL.md: out of date or edited by hand — regenerated "
        "by this sync (backend: claude_code)\n" + DONE,
    )
    assert "HAND EDIT" not in pointer.read_text(encoding="utf-8")
    assert skill.read_text(encoding="utf-8").startswith("---\n# Generated by squads")


