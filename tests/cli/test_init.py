@pytest.mark.covers("init", "--force")
async def test_force_starts_over_a_configured_directory_and_keeps_its_items(invoke) -> None:
    root = Path.cwd()
    first = await invoke([*MINIMAL, "--no-seed-skills"])
    assert first.exit_code == 0, first.output
    created = await invoke(["create", "task", "Kept", "--author", "manager"])
    assert created.exit_code == 0, created.output
    again = await invoke(["init", "--roles", "qa", "--no-seed-skills", "--force"])
    assert again.exit_code == 0, again.output
    assert flat(again.output) == _created(root, "squads", "qa", "claude_code")
    assert await listed(invoke) == [
        ("ROLE-1", "Catherine Manager"),
        ("TASK-2", "Kept"),
        ("ROLE-3", "Mara Tester"),
    ]


