@pytest.mark.covers("init", "--backend")
async def test_backend_claude_code_writes_the_pointers_settings_and_claude_md(invoke) -> None:
    root = Path.cwd()
    result = await invoke([*MINIMAL, "--backend", "claude_code"])
    assert result.exit_code == 0, result.output
    assert flat(result.output) == _created(root, "squads", "manager", "claude_code")
    assert agent_files(root) == [".claude/agents/manager.md", ".claude/settings.json", "CLAUDE.md"]
    pointer = (root / ".claude/agents/manager.md").read_text(encoding="utf-8").split("\n")
    assert "name: manager" in pointer
    assert "You are **Catherine Manager**, the manager on this project." in pointer
    assert any(
        line.startswith("This pointer file itself is regenerated by `sq sync`") for line in pointer
    )
    assert MANAGER in region(root / "CLAUDE.md")


@pytest.mark.covers("init", "--backend")
async def test_backend_agents_md_writes_only_the_agents_md_region(invoke) -> None:
    root = Path.cwd()
    result = await invoke([*MINIMAL, "--backend", "agents_md"])
    assert result.exit_code == 0, result.output
