@pytest.mark.covers("init", "--roles")
async def test_a_terminal_without_default_names_asks_for_each_role_name(
    invoke, monkeypatch
) -> None:
    monkeypatch.setattr("squads._cli._main._is_tty", lambda: True)
    root = Path.cwd()
    result = await invoke(
        ["init", "--roles", "manager,qa", "--no-seed-skills"], input="Zed One\n\n"
    )
    assert result.exit_code == 0, result.output
    prompts, border, panel = result.output.partition("╭")
    assert prompts == (
        "Name for 'manager' (Enter to keep default 'Catherine Manager'): Zed One\n"
        "Name for 'qa' (Enter to keep default 'Mara Tester'): \n"
    )
    assert flat(border + panel) == _created(root, "squads", "manager,qa", "claude_code")
    assert await listed(invoke) == [("ROLE-1", "Zed One"), ("ROLE-2", "Mara Tester")]


